import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const userId = getArgument('--user');
const outputPath = fileURLToPath(new URL('../src/data/publications-scholar.bib', import.meta.url));

if (!userId) {
  throw new Error('Missing Google Scholar user ID. Pass it with --user <id>.');
}

const profileUrl = new URL('https://scholar.google.com/citations');
profileUrl.search = new URLSearchParams({
  user: userId,
  hl: 'en',
  pagesize: '100',
  view_op: 'list_works',
  sortby: 'pubdate',
}).toString();

const profileHtml = await fetchHtml(profileUrl);
const citationPattern = new RegExp(`citation_for_view=(${escapeRegExp(userId)}:[^&"']+)`, 'g');
const citationIds = [...new Set([...profileHtml.matchAll(citationPattern)].map((match) => decodeHtml(match[1])))];

if (citationIds.length === 0) {
  throw new Error('Google Scholar returned no publications. The request may have been blocked.');
}

const publications = [];

for (const citationId of citationIds) {
  const detailUrl = new URL('https://scholar.google.com/citations');
  detailUrl.search = new URLSearchParams({
    view_op: 'view_citation',
    hl: 'en',
    user: userId,
    citation_for_view: citationId,
  }).toString();

  const detailHtml = await fetchHtml(detailUrl);
  publications.push(parsePublication(detailHtml, detailUrl, citationId));
  await delay(150);
}

const previousCount = await getPreviousEntryCount(outputPath);
const minimumSafeCount = previousCount > 0 ? Math.ceil(previousCount * 0.8) : 1;

if (publications.length < minimumSafeCount) {
  throw new Error(
    `Refusing to replace ${previousCount} existing entries with only ${publications.length}; the Scholar response may be incomplete.`
  );
}

publications.sort((a, b) => b.year - a.year || a.title.localeCompare(b.title));

const header = [
  '% Generated by npm run sync:publications. Do not edit this file manually.',
  `% Source: https://scholar.google.com/citations?user=${userId}`,
  '% Put hand-curated additions or overrides in publications.bib.',
  '',
].join('\n');

await writeFile(outputPath, `${header}${publications.map(toBibTeX).join('\n\n')}\n`, 'utf8');
console.log(`Synced ${publications.length} publications from Google Scholar.`);

function getArgument(name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

async function fetchHtml(url) {
  let lastError;

  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await fetch(url, {
        headers: {
          'user-agent':
            'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131 Safari/537.36',
        },
        signal: AbortSignal.timeout(30_000),
      });

      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const html = await response.text();

      if (/unusual traffic|not a robot|captcha/i.test(html)) {
        throw new Error('Google Scholar returned an automated-traffic challenge');
      }

      return html;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await delay(attempt * 1_000);
    }
  }

  throw new Error(`Unable to fetch ${url}: ${lastError instanceof Error ? lastError.message : lastError}`);
}

function parsePublication(html, detailUrl, citationId) {
  const fields = new Map(
    [
      ...html.matchAll(
        /<div class="gsc_oci_field">([\s\S]*?)<\/div><div class="gsc_oci_value"[^>]*>([\s\S]*?)<\/div>/g
      ),
    ].map((match) => [plainText(match[1]), plainText(match[2])])
  );

  const titleMatch = html.match(/<meta property="og:title" content="([\s\S]*?)">/);
  const title = titleMatch ? decodeHtml(titleMatch[1]).replace(/[‪‬]/g, '').trim() : '';
  const authors = fields.get('Authors') ?? '';
  const date = fields.get('Publication date') ?? '';
  const yearMatch = date.match(/\b(19|20)\d{2}\b/);
  const year = yearMatch ? Number.parseInt(yearMatch[0], 10) : Number.NaN;

  if (!title || !authors || Number.isNaN(year)) {
    throw new Error(`Scholar citation ${citationId} is missing a title, authors, or publication year.`);
  }

  const journal = fields.get('Journal');
  const source = fields.get('Source');
  const conference = fields.get('Conference');
  const book = fields.get('Book');
  const institution = fields.get('Institution');
  const publisher = fields.get('Publisher');
  const venue = journal ?? source ?? conference ?? book ?? institution ?? publisher ?? 'Google Scholar';
  const externalUrlMatch = html.match(/id="gsc_oci_title_gg"[\s\S]*?<a href="([^"]+)"/);

  return {
    citationKey: `scholar${citationId
      .split(':')
      .at(-1)
      ?.replace(/[^a-z0-9]/gi, '')
      .toLowerCase()}`,
    type: journal || source ? 'article' : conference ? 'inproceedings' : book ? 'book' : 'misc',
    title,
    authors: authors
      .split(/,\s*/)
      .map((author) => author.trim())
      .filter(Boolean)
      .join(' and '),
    year,
    venueField:
      journal || source
        ? 'journal'
        : conference
          ? 'booktitle'
          : institution
            ? 'school'
            : publisher
              ? 'publisher'
              : 'howpublished',
    venue,
    volume: fields.get('Volume'),
    number: fields.get('Issue'),
    pages: fields.get('Pages'),
    publisher,
    url: externalUrlMatch ? decodeHtml(externalUrlMatch[1]) : detailUrl.toString(),
    scholar: detailUrl.toString(),
  };
}

function toBibTeX(publication) {
  const fields = [
    ['title', publication.title],
    ['author', publication.authors],
    [publication.venueField, publication.venue],
    ['year', String(publication.year)],
    ['volume', publication.volume],
    ['number', publication.number],
    ['pages', publication.pages],
    ...(publication.venueField !== 'publisher' ? [['publisher', publication.publisher]] : []),
    ['url', publication.url],
    ['scholar', publication.scholar],
  ].filter(([, value]) => value);

  const body = fields.map(([key, value]) => `  ${key} = {${escapeBibValue(value)}},`).join('\n');
  return `@${publication.type}{${publication.citationKey},\n${body}\n}`;
}

function escapeBibValue(value) {
  return value.replace(/[{}]/g, '').replace(/\\/g, '').replace(/\s+/g, ' ').trim();
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function plainText(value) {
  return decodeHtml(value.replace(/<[^>]+>/g, ' '))
    .replace(/[‪‬]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function decodeHtml(value) {
  const namedEntities = {
    amp: '&',
    apos: "'",
    gt: '>',
    lt: '<',
    nbsp: ' ',
    quot: '"',
  };

  return value.replace(/&(#x[\da-f]+|#\d+|[a-z]+);/gi, (entity, code) => {
    if (code.startsWith('#x')) return String.fromCodePoint(Number.parseInt(code.slice(2), 16));
    if (code.startsWith('#')) return String.fromCodePoint(Number.parseInt(code.slice(1), 10));
    return namedEntities[code.toLowerCase()] ?? entity;
  });
}

async function getPreviousEntryCount(path) {
  try {
    const contents = await readFile(path, 'utf8');
    return (contents.match(/^@/gm) ?? []).length;
  } catch (error) {
    if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') return 0;
    throw error;
  }
}

function delay(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}
